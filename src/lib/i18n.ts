export function translate(
  language: ResolvedLanguage,
  key: TranslationKey,
  values: Record<string, string | number> = {}
) {
  const template = dictionaries[language]?.[key] ?? en[key];

  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!Object.prototype.hasOwnProperty.call(values, name)) return `{${name}}`;
    const value = values[name];
    // Counts are interpolated often enough that localizing them centrally is
    // better than calling Intl.NumberFormat at every call site.
    if (name === "count" && typeof value === "number") {
      return formatCount(value, language);
    }
    return String(value);
  });
}

export function useI18n() {
  const language = useSettingsStore((state) => state.resolvedLanguage);

  const t = useCallback(
    (key: TranslationKey, values?: Record<string, string | number>) =>
      translate(language, key, values),
    [language]
  );

  return { language, t };
}
